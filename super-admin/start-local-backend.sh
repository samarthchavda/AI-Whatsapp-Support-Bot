#!/usr/bin/env bash
# Runs the normal Kwickbot backend (../backend) against the LOCAL copy of the
# database. Nothing here can reach production:
#
#  - It starts from super-admin/local-backend, so the backend loads that
#    folder's .env (generated below), never backend/.env.
#  - That .env lists every variable name from backend/.env with a blank or
#    local value, so code that later loads backend/.env without override
#    cannot fill in production keys.
#  - guard.js is preloaded: it stops the process if anything connects to a
#    MongoDB other than 127.0.0.1, and blocks every outbound network
#    connection (email, WhatsApp/Meta, Razorpay, Gemini, Shopify, Atlas).
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
BACKEND="$HERE/../backend"
RUN_DIR="$HERE/local-backend"
LOCAL_URI="mongodb://127.0.0.1:27017/kwickbot_superadmin_local"
PORT="${LOCAL_BACKEND_PORT:-5002}"

if ! mongosh "$LOCAL_URI" --quiet --eval 'db.admins.estimatedDocumentCount()' 2>/dev/null | grep -qE '^[1-9]'; then
  echo "The local copy is empty. Run: super-admin/local-db/copy-from-production.sh" >&2
  exit 1
fi

# Local-only JWT secrets, created once. Production sessions don't work here and
# local sessions don't work in production.
SECRETS="$RUN_DIR/.local-secrets"
if [ ! -f "$SECRETS" ]; then
  umask 077
  printf 'JWT_ACCESS_SECRET=%s\nJWT_REFRESH_SECRET=%s\n' "$(openssl rand -hex 32)" "$(openssl rand -hex 32)" > "$SECRETS"
fi
# Shared key between the local backend's checkout hook and the local super-admin API
if ! grep -q '^INTERNAL_API_KEY=' "$SECRETS"; then
  printf 'INTERNAL_API_KEY=%s\n' "$(openssl rand -hex 24)" >> "$SECRETS"
fi
INTERNAL_KEY="$(grep '^INTERNAL_API_KEY=' "$SECRETS" | cut -d= -f2-)"

LOCAL_VALUES="$(cat <<EOF
MONGODB_URI=$LOCAL_URI
PORT=$PORT
NODE_ENV=development
NODE_APP_INSTANCE=1
BACKEND_URL=http://kwickbot-local.invalid
FRONTEND_URL=http://localhost:5173
ALLOWED_ORIGINS=http://localhost:5173
$(grep -E '^JWT_(ACCESS|REFRESH)_SECRET=' "$SECRETS")
SUPER_ADMIN_API_URL=http://127.0.0.1:${LOCAL_API_PORT:-5003}/sa-api/v1
SUPER_ADMIN_API_KEY=$INTERNAL_KEY
EOF
)"

{
  echo "# Generated by start-local-backend.sh. Local values only; do not edit."
  echo "$LOCAL_VALUES"
  # Every other key from backend/.env, blanked
  grep -oE '^[A-Za-z_][A-Za-z0-9_]*=' "$BACKEND/.env" | sed 's/=$//' | sort -u | while read -r key; do
    echo "$LOCAL_VALUES" | grep -q "^$key=" || echo "$key="
  done
  # Keys the code reads that may not be in backend/.env
  for key in RESEND_API_KEY META_APP_SECRET META_WEBHOOK_EXTRA_APP_SECRETS ENCRYPTION_KEY REDIS_URL; do
    grep -q "^$key=" "$BACKEND/.env" || echo "$key="
  done
} > "$RUN_DIR/.env"

if grep -qE '^MONGODB_URI=mongodb\+srv|^MONGODB_URI=.*mongodb\.net' "$RUN_DIR/.env"; then
  echo "Refusing to start: local .env points at a remote database." >&2
  exit 1
fi

echo "Local backend on http://localhost:$PORT using $LOCAL_URI"
cd "$RUN_DIR"
exec node -r ./guard.js "$BACKEND/server.js"
